#!/usr/bin/env node
/* wampo — the tether between `sec-tickers.js` and the arm in app.js that reads
 * it. 2026-10-09.
 *
 * WHY A TEST AND NOT A COMMENT. The table is GENERATED and the consumer is
 * hand-written, which is the shape of every twin this project has lost: four
 * browser twins were deleted by a generator editing a block around them, and a
 * predicate's call site has been wrong often enough that the file's own rules
 * say *a tether per predicate is not a tether on the expression the page
 * evaluates.* So this asserts the EXPRESSION — it asks the real `lookupTicker`,
 * through the tracked harness, with the row the page passes.
 *
 * A regenerated table whose keys no longer match the arm's key expression would
 * otherwise fail silently: every row would simply stay blank, which is exactly
 * what the page shows today, so no reader and no count could tell.
 *
 *   node scripts/sec-tickers-test.mjs
 */
import { readFileSync } from "node:fs";
import vm from "vm";
import { buildRenderer } from "./apppath.mjs";

const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const fail = [];
const ok = (cond, what) => { if (!cond) fail.push(what); else console.log(`  ok   ${what}`); };

/* ---- the asset itself ---- */
const asset = readFileSync(`${ROOT}/sec-tickers.js`, "utf8");
ok(/^\/\* wampo — GENERATED by scripts\/gen-sec-tickers\.mjs/.test(asset),
  "sec-tickers.js announces its generator");
const pinM = asset.match(/^const SEC_TICKERS_PIN = (.*);$/m);
ok(!!pinM, "sec-tickers.js carries SEC_TICKERS_PIN");
const PIN = pinM ? JSON.parse(pinM[1]) : null;
ok(PIN && typeof PIN.key === "string" && /^[A-Z]{1,5}X?$/.test(PIN.tk || ""),
  `the pin names a key and a plausible symbol (${PIN && PIN.tk})`);

const APP = readFileSync(`${ROOT}/app.js`, "utf8");

/* ---- the page, with every script index.html loads ---- */
const R = buildRenderer();
const { lookupTicker } = R.fns;

/* the row shape lookupTicker is given: the key is built from f.iss and
 * f.nameRaw, so the pin is split back into exactly those two cells */
function rowFromKey(key, extra) {
  const i = key.indexOf("\u0000");
  const iss = key.slice(0, i), nameRaw = key.slice(i + 1);
  return { iss, nameRaw, name: nameRaw, type: "Mutual fund", value: 1, ...(extra || {}) };
}

/* (1) THE ARM FIRES, and it is the only thing that could answer this row.
 * Without this a table whose keys drifted would read as "no gains" forever. */
if (PIN) {
  const hit = lookupTicker(rowFromKey(PIN.key));
  ok(!!hit && hit.tk === PIN.tk, `the pin resolves through lookupTicker: ${JSON.stringify(PIN.key)} -> ${PIN.tk} (got ${hit ? hit.tk : "null"})`);
  /* (2) AND IT IS NEVER A COMPARABLE. Only asserted answers are in the table;
   * an asterisk here would be the 59.7M-reader decision this ship refused. */
  ok(!!hit && hit.comparable === false, "the pin's answer is ASSERTED, not a comparable");
}

/* (2b) THE BARE-CLASS ARM'S OWN CLAIM, pinned by ack-free key because it is the
 * one gain in this table that turns on WHICH SHARE CLASS of an already-
 * identified series is the answer. Oracle Corporation (101,985 participants)
 * files `Fidelity Worldwide Fund` on $410,529,000 and the matcher answers
 * FWAFX — the `Fidelity ADVISOR Worldwide Fund: Class A`, a different product
 * line sold with a load — as a comparable, which this table never ships. The
 * registry carries a class whose registered name IS `Fidelity Worldwide Fund`,
 * FWWFX, and the filing names exactly that.
 *
 * THIS IS HERE AND NOT IN THE GENERATOR because the generator's own four
 * BARE-CLASS controls read the LIVE `sec-funds.json`, so a registry refresh can
 * make them stale — the `merge-name-test` shape the record says must stay out
 * of CI. This assertion reads only the COMMITTED table and app.js, so it is a
 * property of what shipped: if a later regen stops producing the key, or
 * produces it with an asterisk, CI goes red instead of a reader finding it. */
const BARE_KEY = "\u0000Fidelity Worldwide Fund";
{
  const hit = lookupTicker(rowFromKey(BARE_KEY));
  ok(!!hit && hit.tk === "FWWFX",
    `the bare-class arm still ships: "Fidelity Worldwide Fund" -> FWWFX (got ${hit ? hit.tk : "null"})`);
  ok(!!hit && hit.comparable === false,
    "...ASSERTED, never the Advisor class behind an asterisk");
}

/* (2c) THE FILER'S TYPO, pinned against the COMMITTED table for the same
 * reason as (2b): the generator's own evidence for `MEFS` -> `MFS` is read out
 * of the live `sec-funds.json` (0 of 29,406 rows spell MEFS, 695 spell MFS), so
 * a registry refresh could make a generator-side control stale. This reads only
 * what shipped. `MEFS` is MFS with an inserted E — it names no registrant — and
 * the repair reaches the rows whose product name carries distinctive words of
 * its own, which `registrantAttested` can then confirm. */
{
  const hit = lookupTicker(rowFromKey("\u0000MEFS International Diversification Class R6"));
  ok(!!hit && hit.tk === "MDIZX",
    `the MEFS typo repair still ships: "MEFS International Diversification Class R6" -> MDIZX (got ${hit ? hit.tk : "null"})`);
  ok(!!hit && hit.comparable === false, "...ASSERTED: the filing states Class R6 and the registry registers it");
  /* A MUST-NOT-SEE, and labelled as what it is: no such key exists in either
   * the old table or the new one, so it cannot fail today. It is here because
   * the repair is anchored on a WORD boundary and a later regen that dropped
   * the anchor would start writing keys of this shape — the `AMF` lesson,
   * where `^` and `\b` were each pinned and each could fail. */
  ok(lookupTicker(rowFromKey("\u0000MEFSA Diversified Holdings Fund")) === null,
    "a longer word beginning MEFS is left alone (decorative today, by construction)");
}

/* (2d) AN ADMIRAL SHARE CLASS WITH NO HOUSE, pinned against the COMMITTED table
 * for the same reason as (2b) and (2c): the generator's own evidence is read out
 * of the live `sec-funds.json` — the house set is DERIVED from it — so a registry
 * refresh could make a generator-side control stale. These read only what
 * shipped.
 *
 * Boston Scientific (34,105 participants) files fourteen rows shaped
 * `<product> Adm` with an EMPTY issuer cell, typed `Mutual fund`: the filing
 * states Vanguard's Admiral CLASS and omits the HOUSE. The arm prefixes the one
 * house the registry attests registers an Admiral class and requires the
 * resolved ticker's own registered `className` to state Admiral.
 *
 * ***THE MUST-NOT-SEES ARE THE LOAD-BEARING HALF HERE, because this arm's
 * delivery is bounded by a guard rather than by its own reach.*** It reaches 13
 * of Boston Scientific's 14 rows and `registrantAttested` allows TWO; the eleven
 * refused are the plain index funds, whose registrant `VANGUARD INDEX FUNDS`
 * contributes nothing distinctive beyond `vanguard` — the word the filing omits.
 * So a later regen that started publishing `Growth Index Adm` would mean the
 * guard or the registry moved and the ship's measured figure no longer holds. */
{
  for (const [key, want, what] of [
    ["\u0000500 Index Adm", "VFIAX", "the Admiral arm still ships: `500 Index Adm` -> VFIAX"],
    ["\u0000Cash Reserves Federal MM Adm", "VMRXX", "...and `Cash Reserves Federal MM Adm` -> VMRXX"],
  ]) {
    const hit = lookupTicker(rowFromKey(key));
    ok(!!hit && hit.tk === want, `${what} (got ${hit ? hit.tk : "null"})`);
    ok(!!hit && hit.comparable === false, "...ASSERTED, because the filing states the class and the registry registers it");
  }
  /* the ATTESTATION bound — the motivating row itself, refused */
  ok(lookupTicker(rowFromKey("\u0000Growth Index Adm")) === null,
    "the motivating row `Growth Index Adm` is REFUSED by registrantAttested, as measured (the arm reaches it; the guard withholds it)");
  /* the FOREIGN-HOUSE refusal: attestation ALLOWS this row, because VANGUARD
   * INDEX FUNDS contributes the product word `500` and `American Funds 500 Index
   * Adm` repeats it. Only the name-side house test blocks it, so this pin is the
   * single protection against publishing a Vanguard symbol on a row that names
   * another house outright. */
  for (const n of ["Fidelity Emerging Markets Stock Index Adm", "American Funds 500 Index Adm"]) {
    ok(lookupTicker(rowFromKey(`\u0000${n}`)) === null,
      `a name stating ANOTHER house is refused: ${JSON.stringify(n)}`);
  }
  /* the className condition: Vanguard's twelve Target Retirement series register
   * EXACTLY ONE class, `Investor Shares`, so a filing stating Admiral names no
   * registered class of that fund and the arm must abstain rather than reach for
   * VTINX. Nothing else answers this spelling, so `lookupTicker` is the right
   * instrument here. */
  ok(lookupTicker(rowFromKey("Fidelity\u0000Target Retirement 2040 Fund Admiral")) === null,
    "a Target Retirement row stating Admiral is refused (the registry registers no Admiral class of it)");
  /* ***AND THE SIBLING SPELLING HAD TO BE PINNED AGAINST THE TABLE INSTEAD,
   * because asking `lookupTicker` tested the WRONG RESOLVER.*** `Admiral Shares
   * Target Retirement Income Fund` [iss `The Vanguard Group`] does not resolve
   * to null: `fund-er.js` answers **VTINX, ASSERTED** — pre-existing, nothing to
   * do with this arm, and a named live instance of the owner-gated
   * wrong-share-class family, since the registry registers that fund with one
   * class (`Investor Shares`) and the filing states Admiral. So the claim this
   * arm is responsible for is that the GENERATOR WROTE NO KEY for it, which is
   * what the className condition decides. *There are two resolvers, and a
   * fixture is only as good as the one its own harness asks* — recorded on the
   * `K-1` decoy of 2026-10-11 03:3xZ and met again here. */
  {
    const m = asset.match(/^const SEC_TICKERS = (\{[\s\S]*?\});$/m);
    const T = m ? vm.runInNewContext(`(${m[1]})`) : {};
    const bad = Object.keys(T).filter((k) => /target retirement/i.test(k) && /\badm/i.test(k));
    ok(bad.length === 0,
      `the table writes no Target-Retirement-stating-Admiral key (${bad.length}: ${bad.slice(0, 2).map((x) => JSON.stringify(x)).join(", ")})`);
  }
}

/* (3) IT IS LAST: a row the page's own chain resolves must keep that answer. */
const own = lookupTicker({ name: "Vanguard 500 Index Fund Admiral Shares",
  nameRaw: "Vanguard 500 Index Fund Admiral Shares", iss: "", type: "Mutual fund", value: 1 });
ok(!!own && own.tk === "VFIAX", `the page's own resolver still wins (VFIAX, got ${own ? own.tk : "null"})`);

/* (4) IT NEVER DISPLACES THE FILING'S OWN SYMBOL. `renderRow` publishes `f.tk`
 * whenever lookupTicker returns null, so the arm must stand down there — the
 * filing's own code is a more precise claim about the share class than a
 * registry match on the name. */
if (PIN) {
  const held = lookupTicker(rowFromKey(PIN.key, { tk: "ZZZZX" }));
  ok(held === null, "a row carrying the filing's own f.tk is left alone");
}

/* (5) A MISS IS A BLANK, never a guess. */
ok(lookupTicker({ name: "Qqqq Zzzz Nonexistent Holding 9999", nameRaw: "Qqqq Zzzz Nonexistent Holding 9999",
  iss: "", type: "Mutual fund", value: 1 }) === null, "a name in no table resolves to nothing");

/* (6) THE GENERATOR'S PREMISE. `gen-sec-tickers.mjs` builds its renderer with
 * `secTickers: false`, because its gate is "the page resolves nothing" and a
 * loaded table would make the generator read its own output and write an EMPTY
 * one on the next run. Assert the flag actually disables the arm. */
if (PIN) {
  const G = buildRenderer({ secTickers: false });
  ok(G.fns.lookupTicker(rowFromKey(PIN.key)) === null,
    "secTickers:false disables the arm (the generator cannot read its own output)");
  ok(G.fns.lookupTicker({ name: "Vanguard 500 Index Fund Admiral Shares",
    nameRaw: "Vanguard 500 Index Fund Admiral Shares", iss: "", type: "Mutual fund", value: 1 })?.tk === "VFIAX",
    "...and disabling it leaves the rest of the chain intact");
}

/* (8) A POOLED VEHICLE IS NOT THE REGISTERED FUND, AND THE KEY CANNOT SAY SO.
 * `gen-sec-tickers.mjs` applies fund-er.js's pooled rule PER ROW, but the table
 * it writes is keyed on `(issuer, nameRaw)` and that predicate reads a THIRD
 * input — the filed TYPE cell. So one plan filing cells typed `Government
 * securities` wrote a key that eight plans filing the same cells typed `Pooled
 * separate account` then read, publishing the symbol as fact: 1,750 rows / 307
 * keys / 840 plans / 1,019,442 participants / $16,466,055,303 store-wide.
 * `lookupTicker` now asks the vehicle question itself, per row.
 *
 * BOTH DIRECTIONS, because a blanket refusal would read the same as a gate: the
 * pin must STILL resolve under an honest type cell and must NOT under a pooled
 * one. Without the first half this test would pass against an arm that had
 * simply been deleted. */
if (PIN) {
  for (const t of ["Collective trust", "Separate account", "Pooled separate account", "Managed account"]) {
    ok(lookupTicker(rowFromKey(PIN.key, { type: t })) === null,
      `the vehicle gate withholds the pin on a row typed ${JSON.stringify(t)}`);
  }
  const honest = lookupTicker(rowFromKey(PIN.key, { type: "Mutual fund" }));
  ok(!!honest && honest.tk === PIN.tk,
    "...and the SAME key still resolves on a row typed Mutual fund (a gate, not a deletion)");
  const blank = lookupTicker(rowFromKey(PIN.key, { type: "" }));
  ok(!!blank && blank.tk === PIN.tk,
    "...and on a row whose type cell is blank, which says nothing about the vehicle");
}

/* (8b) THE PREDICATE IS THE SHIPPED ONE, NOT A TWIN. fund-er.js exposes
 * `pooledVehicleRow` precisely so there is no second copy of that expression to
 * drift; assert app.js reaches for it by name and stands DOWN if it is absent. */
ok(/pooledVehicleRow\(f\.name, f\.type \|\| ""\)/.test(APP),
  "app.js asks fund-er.js's own pooledVehicleRow, with the row's filed type");
ok(/typeof pooledVehicleRow !== "function"\s*\n?\s*\|\|/.test(APP),
  "...and a missing predicate denies the arm rather than publishing unchecked");

/* (8c) THE `f.nameRaw` CALL IS UNREACHABLE FOR ANY KEY IN THIS TABLE, and it is
 * kept and LABELLED rather than deleted: `f.name` is `clean(f.nameRaw)`, so the
 * two differ only through the rule's NAME disjuncts, and the generator refuses
 * a row on EITHER spelling before writing its key. Asserted over the committed
 * table rather than argued, so that if the generator ever stops asking the name
 * question this stops being decorative and the test says which claim moved. */
{
  /* the committed table's own keys, read out of the asset the page loads */
  const m = asset.match(/^const SEC_TICKERS = (\{[\s\S]*?\});$/m);
  ok(!!m, "the asset carries a SEC_TICKERS object literal this test can read");
  const TABLE = m ? vm.runInNewContext(`(${m[1]})`) : {};
  ok(Object.keys(TABLE).length > 1000, `the table parses (${Object.keys(TABLE).length} keys)`);
  const names = Object.keys(TABLE).map((k) => k.slice(k.indexOf("\u0000") + 1));
  /* ASK THE PREDICATE, NOT THE CHAIN. The first version of this check built a
   * row from the key's NAME half with a blank issuer and called `lookupTicker`:
   * the key then missed and all 4,480 nulls read as "pooled by name". *A clean
   * null reports on the query.* So slice fund-er.js's rule, as the generator
   * does, and ask it directly — with a control in each direction first. */
  const FE = readFileSync(`${ROOT}/fund-er.js`, "utf8");
  const tcM = FE.match(/^const TRUST_CLASS = .*$/m);
  const poM = FE.match(/^ {2}const pooled = [\s\S]*?\.test\(type \|\| ""\);$/m);
  ok(!!tcM && !!poM, "fund-er.js's pooled rule can still be sliced (the generator needs this too)");
  const g = {};
  if (tcM && poM) vm.runInNewContext(`${tcM[0]}\n__out.pooledRow = (name, type) => {\n${poM[0]}\n  return !!pooled;\n};`, { __out: g });
  /* both controls PROBED, not guessed: my first positive here was `Galliard
   * Stable Return Fund`, which carries no pooled token at all (`stable return`
   * is not `stable value`) and reads false — *pick a control independently
   * known correct.* */
  ok(g.pooledRow && g.pooledRow("Putnam Stable Value Fund", "") === true
    && g.pooledRow("Vanguard Target Retirement Trust Flex", "") === true
    && g.pooledRow("Fidelity 500 Index Fund", "") === false,
    "the sliced rule answers the NAME question in both directions");
  const byName = g.pooledRow ? names.filter((n) => g.pooledRow(n, "")) : ["slice failed"];
  ok(byName.length === 0,
    `no key in the table is pooled by NAME alone, so the nameRaw call is decorative (${byName.length} would be: ${byName.slice(0, 3).map((x) => JSON.stringify(x)).join(", ")})`);
}

/* (7) THE BROWSER TWIN OF THE KEY. app.js must build the key from the same two
 * cells in the same order; a transposition would make every lookup miss and
 * nothing else would notice. Asserted against the SOURCE, because the shape of
 * the key is the one thing the test above cannot distinguish from a drifted
 * table. */
ok(/SEC_TICKERS\[\(f\.iss \|\| ""\) \+ "\\u0000" \+ \(f\.nameRaw \|\| f\.name \|\| ""\)\]/.test(APP),
  "app.js builds the key as (f.iss) NUL (f.nameRaw || f.name)");

if (fail.length) {
  console.error(`\nsec-tickers-test: ${fail.length} FAILED`);
  for (const f of fail) console.error(`  FAIL ${f}`);
  process.exit(1);
}
console.log("\nsec-tickers-test: OK");
