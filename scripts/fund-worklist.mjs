#!/usr/bin/env node
/* wampo — THE FUND WORKLIST: which fund names to source, in reader order.
 *
 * wampo publishes 1.7M holding rows carrying 323,933 distinct fund-name
 * spellings, and the instinct has always been to DERIVE each one's identity
 * from the filed string -- regex tables, matchers, abbreviation arms. That is
 * why the ticker column resolves 44% and the fee column is 273k invented
 * numbers and 587k regex estimates with essentially nothing sourced.
 *
 * The distribution says the derivation approach is unnecessary. Ranked by
 * READERS, the top 100 names reach 64.8% of everyone with a published menu and
 * the top 1,000 reach 91.2%. It is a ~1,000-row reference-data job, not a
 * 324,000-row inference problem.
 *
 * This writes that worklist. It sources nothing itself -- a ticker, a fee and a
 * return are FACTS THAT MUST BE SOURCED, and `data/fund-facts.json` is the only
 * place they may live.
 *
 * Run: node scripts/fund-worklist.mjs [--top 1000] [--out data/fund-worklist.json]
 */
import { readFileSync, readdirSync } from "node:fs";
import { loadPlans } from "/home/user/no-app/scripts/lib-schema.mjs";
import { servedLineup } from "/home/user/no-app/scripts/lib-ledger.mjs";
const ROOT="/home/user/no-app";
const lidx=JSON.parse(readFileSync(`${ROOT}/lineups-index.json`,"utf8")).plans;
const d=loadPlans();
const members=new Map();
for(const row of d.rows){
  const p={ack:d.get(row,"ack"),mtiaAck:d.get(row,"mtiaAck"),ein:d.get(row,"ein"),pn:d.get(row,"pn"),
    participants:+d.get(row,"partEOY")||+d.get(row,"participants")||0};
  const s=servedLineup(p,lidx); if(!s.ack) continue;
  if(!members.has(s.ack)) members.set(s.ack,[]); members.get(s.ack).push(p);
}
/* key on the NAME a human would look up, normalised lightly */
const norm=(s)=>String(s||"").toUpperCase().replace(/[^A-Z0-9]+/g," ").trim();
const fam=new Map();
for(const sh of readdirSync(`${ROOT}/data/lineups`)){
  if(!sh.endsWith(".json")) continue;
  const shard=JSON.parse(readFileSync(`${ROOT}/data/lineups/${sh}`,"utf8"));
  for(const [ack,e] of Object.entries(shard)){
    const mem=members.get(ack); if(!mem||!e||!e.confident||!Array.isArray(e.funds)) continue;
    for(const f of e.funds){
      const k=norm(f.name); if(!k||k.length<4) continue;
      let g=fam.get(k); if(!g){g={rows:0,plans:new Map(),val:0,ex:String(f.name)};fam.set(k,g);}
      g.rows++; g.val+=+f.value||0;
      for(const q of mem) g.plans.set(`${q.ein}|${q.pn}`,q.participants);
    }
  }
}
const list=[...fam.values()].map(g=>({...g,ppl:[...g.plans.values()].reduce((a,b)=>a+b,0),np:g.plans.size}))
  .sort((a,b)=>b.ppl-a.ppl);
const totalPpl=(()=>{const m=new Map();for(const g of fam.values())for(const [k,v] of g.plans)m.set(k,v);return [...m.values()].reduce((a,b)=>a+b,0);})();
console.log(`distinct fund names (normalised): ${list.length.toLocaleString()}`);
console.log(`total readers with a published menu: ${Math.round(totalPpl).toLocaleString()}\n`);
const n=(x)=>Math.round(x).toLocaleString();
for(const cut of [100,250,500,1000,2500,5000]){
  const m=new Map(); let rows=0;
  for(const g of list.slice(0,cut)){ rows+=g.rows; for(const [k,v] of g.plans) m.set(k,v); }
  const ppl=[...m.values()].reduce((a,b)=>a+b,0);
  console.log(`top ${String(cut).padStart(5)} names  ->  ${n(rows).padStart(9)} rows · ${n(ppl).padStart(11)} readers (${(100*ppl/totalPpl).toFixed(1)}% of all)`);
}
console.log("\n--- the 15 most-held funds, which is where anyone would start ---");
for(const g of list.slice(0,15)) console.log(`   ${n(g.ppl).padStart(10)} ppl · ${String(g.np).padStart(5)} plans · $${n(g.val).padStart(15)}  ${g.ex.slice(0,52)}`);

/* ---- write the worklist ------------------------------------------------- */
import { writeFileSync } from "node:fs";
const argv=process.argv.slice(2);
const one=(f,d)=>{const i=argv.indexOf(f);return i>=0&&argv[i+1]?argv[i+1]:d;};
const TOP=+one("--top","1000");
const OUT=one("--out","data/fund-worklist.json");
const already=(()=>{ try{ const j=JSON.parse(readFileSync(`${ROOT}/data/fund-facts.json`,"utf8"));
  return new Set(Object.keys(j.funds||{}).concat(Object.keys(j.vehicles||{}))); }catch{ return new Set(); } })();
const work=list.slice(0,TOP).map((g,i)=>({
  rank:i+1, name:g.ex, rows:g.rows, plans:g.np, readers:Math.round(g.ppl), value:Math.round(g.val) }));
const cum=(()=>{const m=new Map();for(const g of list.slice(0,TOP))for(const [k,v] of g.plans)m.set(k,v);
  return Math.round([...m.values()].reduce((a,b)=>a+b,0));})();
writeFileSync(`${ROOT}/${OUT}`,JSON.stringify({
  _schema:"The fund names to SOURCE, ranked by readers affected. Generated by scripts/fund-worklist.mjs; it sources nothing. A ticker, an expense ratio and a return are facts that must be sourced, and data/fund-facts.json is the only place they may live.",
  generated:new Date().toISOString().slice(0,10),
  distinctNamesInStore:list.length, readersWithAMenu:Math.round(totalPpl),
  top:TOP, readersCovered:cum, sharePct:+(100*cum/totalPpl).toFixed(1),
  alreadySourced:already.size, work},null,1)+"\n");
console.log(`\nwrote ${OUT}: top ${n(TOP)} names · ${n(cum)} readers (${(100*cum/totalPpl).toFixed(1)}%) · ${already.size} already in fund-facts.json`);
