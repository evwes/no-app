#!/usr/bin/env node
/* wampo — map Form 5500 sponsor names to listed-company tickers.
 *
 * WHY THIS IS NOT A LOOKUP. A Form 5500 is filed by a legal entity, and that
 * entity is routinely not the listed company:
 *   GE Vernova's plan is filed by "Ropcor, Inc."
 *   Alphabet's is filed by "Google LLC"
 * and the reverse trap is worse — an entity whose name merely BEGINS with a
 * listed company's is often a different institution entirely:
 *   "General Electric Credit Union"    is not General Electric
 *   "McGraw-Hill Education Holdings"   was divested from S&P Global in 2013
 *   "Target Foundation"                is not Target
 * The old matcher ended in a bare startsWith and produced exactly those.
 *
 * So this is built the way the fund matcher was built, and for the same reason:
 * coverage is easy and precision is the product. Every rule below exists to
 * refuse a match, and the script's real output is the SAMPLE it prints for
 * hand review, not the count.
 *
 * The curated list in companies.json stays. It is not redundant: it carries the
 * cases name matching CANNOT reach (Ropcor -> GEV, Google -> GOOGL), each of
 * which is a fact about corporate structure that no string comparison knows.
 *
 * Usage:
 *   node scripts/match-sponsors.mjs [--companies sec-companies.json] [--sample 40]
 *   node scripts/match-sponsors.mjs --min-participants 5000   (the review slice)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const COMPANIES = arg("--companies", path.join(root, "sec-companies.json"));
const SAMPLE = +arg("--sample", 40);
const MIN_PARTS = +arg("--min-participants", 0);

/* ---- normalization ---------------------------------------------------------
 * Corporate suffixes carry no identity and differ freely between the SEC title
 * and the Form 5500 sponsor name ("APPLE INC" vs "Apple Inc."). Everything else
 * is kept, because everything else is what tells two entities apart. */
const SUFFIX = new Set(["inc", "incorporated", "corp", "corporation", "co", "company",
  "companies", "holding", "holdings", "group", "llc", "llp", "lp", "plc", "ltd", "limited",
  "sa", "nv", "ag", "se", "the", "and", "of", "&"]);
const norm = (s) => String(s).toLowerCase()
  .replace(/[^a-z0-9 ]/g, " ").replace(/\s+/g, " ").trim();
/* A bare "s" is the possessive apostrophe that norm() just turned into a space,
 * and it is NOT a distinguishing token. Left in, "Charlie's Holdings, Inc."
 * keyed as two tokens and so escaped the single-token rule below — which is how
 * a Maine car dealership ("Charlie's Motor Mall") and a Toledo one both drew
 * CHUC, a vape company. */
const tokens = (s) => norm(s).split(" ").filter((w) => w && w !== "s" && !SUFFIX.has(w));

/* An entity whose name begins with a listed company's but which is NOT that
 * company. This is the guard that matters, and it is about the KIND of
 * institution named, not about extra words: most extra words are innocent
 * ("UnitedHealth Group Incorporated", "Union Pacific Railroad Company",
 * "Medtronic Puerto Rico Operations" are all the same employer). */
const NOT_THE_SAME_EMPLOYER = /\b(credit union|federal credit|savings bank|foundation|charitable|trust|university|college|school|academy|hospital|health system|medical center|clinic|church|ministries|diocese|synagogue|temple|municipal|county|city of|state of|township|authority|cooperative|co op|mutual insurance|fraternal|union local|local \d+|district council|pension|welfare fund|association|society|institute|museum|library)\b/i;


/* Generated by `--tokens` below and committed, because the counts it is derived
 * from need the whole plan universe and build-data.mjs runs BEFORE that universe
 * exists. Regenerate it whenever the universe or the SEC list moves. */
let SAFE_SINGLE = new Set();
try {
  SAFE_SINGLE = new Set(JSON.parse(fs.readFileSync(path.join(root, "scripts/sponsor-single-tokens.json"), "utf8")).tokens);
} catch { /* absent -> every single-token name goes to review, which is the safe direction */ }

const raw = JSON.parse(fs.readFileSync(COMPANIES, "utf8"));
const companies = raw.companies.map(([ticker, title, cik]) => ({ ticker, title, cik, key: tokens(title) }))
  .filter((c) => c.key.length);

/* Index by leading token so a sponsor only considers plausible companies.
 * Without it this is 110k sponsors x 10k companies and does not finish. */
const byLead = new Map();
for (const c of companies) {
  const arr = byLead.get(c.key[0]) || [];
  arr.push(c);
  byLead.set(c.key[0], arr);
}
for (const arr of byLead.values()) arr.sort((a, b) => b.key.length - a.key.length);

export function matchSponsor(sponsorName) {
  const st = tokens(sponsorName);
  if (!st.length) return null;
  const cands = byLead.get(st[0]);
  if (!cands) return null;

  const hits = [];
  const singles = [];   // single-token prefix candidates -> human review, not the site
  for (const c of cands) {
    if (c.key.length > st.length) continue;
    let all = true;
    for (let i = 0; i < c.key.length; i++) if (st[i] !== c.key[i]) { all = false; break; }
    if (!all) continue;                                  // must match from the START
    const rest = st.slice(c.key.length);
    /* A SINGLE-TOKEN company name may only match EXACTLY. Measured over the
     * 625 new attributions on sponsors with >=5,000 participants: 479 exact,
     * 42 multi-token prefix, 104 single-token prefix — and every error found by
     * hand review sat in that last group:
     *   "Compass Group Usa"        -> COMP  (Compass, Inc. is a US brokerage;
     *                                        Compass Group is UK foodservice)
     *   "Banner Health"            -> BANR  (a bank holding company)
     *   "Citizens Financial Group" -> CIA   (a Texas insurer, not CFG)
     *   "Latham & Watkins Llp"     -> SWIM  (a law firm, matched to pools)
     *   "Team Public Choices Llc"  -> TISI
     * A one-word company name is a prefix of too much of the world. Twelve
     * sampled multi-token prefix matches were all correct, so the boundary is
     * token count, not a hand-listed vocabulary of "common" words — that list
     * was a guess and would never have caught Banner or Citizens.
     *
     * This DOES cost real matches (Dow, AstraZeneca, Fiserv, CBRE, Aon, Alcon
     * are single-token companies whose prefix matches were correct). Those go
     * to the review queue below and reach the site through companies.json,
     * where a human has confirmed them. Automation where it is provably safe;
     * review where it is not.
     *
     * REVISED 2026-08-24, second measurement. The rule above said "may only
     * match EXACTLY", and a sample of the sub-5,000-participant tail showed
     * that exactness is worth nothing here, because suffix stripping MANUFACTURES
     * it: "Superior Holding, Inc." and "SUPERIOR GROUP OF COMPANIES, INC." both
     * reduce to the single token "superior" and scored [exact]. So did
     * "Parsons Group, Llc" against PARSONS CORP. A one-token company name is
     * unsafe in every form, not only as a prefix — the whole match rests on one
     * common word — so all of them go to review now.
     *
     * FOURTH measurement. Refusing every single-token name also lost Kroger,
     * Insperity, DaVita, Cintas, Albertsons, Tenet — brands that are not
     * ambiguous at all. The difference between those and "Superior" is whether
     * the word is COINED or ORDINARY, and that is measurable in data already
     * here: how many distinct sponsors in the 110k-plan universe lead with the
     * word, and how many SEC registrants use it anywhere.
     *   kroger 1 sponsor / 1 registrant      superior 105 / 4
     *   cintas 1 / 1                         national 397 / 71
     *   davita 1 / 1                         premier 155 / 5
     * Scored over 22 known-good and 15 known-bad single tokens, "<=2 sponsors
     * lead AND <=3 registrants" admits 16 of the good and NONE of the bad —
     * including the three errors that motivated this rule (parsons 4 sponsors,
     * charlie 4, latham 3). The safe list is generated, not hand-written:
     *   node scripts/match-sponsors.mjs --tokens
     * FedEx (4 sponsors) and Tyson (3) fall outside it and go to review, where
     * a human confirms them into companies.json. */
    if (c.key.length === 1 && !SAFE_SINGLE.has(c.key[0])) { singles.push({ c, rest }); continue; }
    /* THIRD measurement, same day. With single-token names gone the tail still
     * carried errors, and they shared a shape: a TWO-token company name of
     * ordinary English, plus extra sponsor words that name a different business.
     *   "National Bank Of Middlebury"      -> NBHC (National Bank Holdings)
     *   "James River Home Health Care Llc" -> JRVR (James River Group, an insurer)
     * Neither is caught by NOT_THE_SAME_EMPLOYER, and neither can be: the
     * disqualifying words ("of middlebury") name nothing at all.
     *
     * I tried scoring distinctiveness by how many sponsors in the universe
     * share the key — it separated these two (5 and 8 sharers) from Best Buy
     * (3) and Colliers (4), but on four data points that is a fitted threshold,
     * not a measurement, so it is not the rule.
     *
     * The rule is structural instead: a match on extra words needs a company
     * name long enough to be an identification on its own. Two ordinary words
     * are not. This costs correct matches — Best Buy Enterprise Services,
     * Harley-Davidson Motor Company Group, Host Hotels & Resorts L.P. — and
     * they go to review like the others, because a lost match is a blank field
     * and a wrong match is a wrong company on a live page. */
    if (rest.length && c.key.length < 3) { singles.push({ c, rest, why: "short name + extra words" }); continue; }
    if (NOT_THE_SAME_EMPLOYER.test(rest.join(" "))) continue;
    hits.push({ c, extra: rest.length, exact: rest.length === 0 });
  }
  if (!hits.length) return singles.length ? { review: true, ticker: singles[0].c.ticker, title: singles[0].c.title, why: "single-token prefix" } : null;

  // Prefer the longest company name matched (most specific), then exactness.
  hits.sort((a, b) => b.c.key.length - a.c.key.length || a.extra - b.extra);
  const best = hits[0];
  // AMBIGUITY: two different companies matching equally well means the sponsor
  // name does not identify one of them. Refuse rather than pick.
  const tied = hits.filter((h) => h.c.key.length === best.c.key.length && h.c.ticker !== best.c.ticker);
  if (tied.length) return null;
  return { ticker: best.c.ticker, title: best.c.title, cik: best.c.cik,
    why: best.exact ? "exact" : "prefix+" + best.extra };
}

/* --tokens: regenerate the safe single-token list. Two counts, both from data
 * already in the repo, both measured rather than chosen:
 *   leadSponsors  distinct sponsor names in the universe starting with the word
 *   registrants   SEC registrants using the word anywhere in their title
 * Thresholds 2 and 3 were set by scoring 22 known-good and 15 known-bad tokens;
 * see the note in matchSponsor. */
if (process.argv.includes("--tokens")) {
  const j = JSON.parse(fs.readFileSync(path.join(root, "plans-list.json"), "utf8"));
  const lead = new Map(), seen = new Set();
  for (const nm of j.cols.name) {
    const s = String(nm || "").toLowerCase();
    if (seen.has(s)) continue;
    seen.add(s);
    const k = tokens(s);
    if (k.length) lead.set(k[0], (lead.get(k[0]) || 0) + 1);
  }
  const reg = new Map();
  for (const c of companies) for (const w of new Set(c.key)) reg.set(w, (reg.get(w) || 0) + 1);

  const out = [];
  for (const c of companies) {
    if (c.key.length !== 1) continue;
    const w = c.key[0];
    if ((lead.get(w) || 0) <= 2 && (reg.get(w) || 0) <= 3) out.push(w);
  }
  const tks = [...new Set(out)].sort();
  fs.writeFileSync(path.join(root, "scripts/sponsor-single-tokens.json"),
    JSON.stringify({ generated: new Date().toISOString(),
      rule: "single-token company name ships only when <=2 distinct universe sponsors lead with it AND <=3 SEC registrants use it",
      count: tks.length, tokens: tks }, null, 1) + "\n");
  console.log(`wrote scripts/sponsor-single-tokens.json: ${tks.length} safe single-token company names`);
  process.exit(0);
}

if (process.argv[1] && process.argv[1].endsWith("match-sponsors.mjs")) {
  const j = JSON.parse(fs.readFileSync(path.join(root, "plans-list.json"), "utf8"));
  const c = j.cols, n = c.name.length;
  const curated = new Set();
  try {
    for (const x of JSON.parse(fs.readFileSync(path.join(root, "scripts/companies.json"), "utf8")).companies)
      curated.add(x.ticker);
  } catch { /* optional */ }

  let scanned = 0, matched = 0, already = 0;
  const rows = [], review = [];
  for (let i = 0; i < n; i++) {
    if (c.parts[i] < MIN_PARTS) continue;
    scanned++;
    const r = matchSponsor(c.name[i] || "");
    if (!r) continue;
    matched++;
    if (c.tk[i]) { already++; continue; }
    const rec = { name: c.name[i], ticker: r.ticker, title: r.title, why: r.why,
      parts: c.parts[i], curated: curated.has(r.ticker) };
    (r.review ? review : rows).push(rec);
  }
  rows.sort((a, b) => b.parts - a.parts);
  review.sort((a, b) => b.parts - a.parts);

  console.log(`sponsors scanned      : ${scanned.toLocaleString()}${MIN_PARTS ? ` (>= ${MIN_PARTS} participants)` : ""}`);
  console.log(`  matched a registrant: ${matched.toLocaleString()}`);
  console.log(`  already had a ticker: ${already.toLocaleString()}`);
  console.log(`  AUTOMATIC (ships)   : ${rows.length.toLocaleString()}`);
  /* Deduplicate the queue by SPONSOR, not by plan. A human reviewing it is
   * deciding "is this entity that company", which is one decision however many
   * plans the entity files. */
  const bySponsor = new Map();
  for (const r of review) {
    const k = r.name.toLowerCase();
    const cur = bySponsor.get(k);
    if (!cur) bySponsor.set(k, { ...r, plans: 1 });
    else { cur.plans++; cur.parts = Math.max(cur.parts, r.parts); }
  }
  const queue = [...bySponsor.values()].sort((a, b) => b.parts - a.parts);
  console.log(`  REVIEW QUEUE        : ${queue.length.toLocaleString()} sponsors (${review.length.toLocaleString()} plans) — refused, does NOT ship\n`);

  /* The review queue is written out, not just printed. Hand-confirmed entries
   * go into companies.json; that is the only path by which a refused match
   * reaches the site. */
  const qp = path.join(root, "docs/sponsor-review-queue.json");
  fs.writeFileSync(qp, JSON.stringify(queue, null, 1) + "\n");
  console.log(`review queue written  : ${path.relative(root, qp)}\n`);

  console.log(`Largest new attributions — READ THESE. A wrong one is a wrong company on a live page.\n`);
  for (const r of rows.slice(0, SAMPLE)) {
    console.log(`  ${r.ticker.padEnd(6)} ${String(r.parts).padStart(7)}p  ${r.name.slice(0, 44).padEnd(46)} -> ${r.title.slice(0, 40)}  [${r.why}]`);
  }
}
